import { expect, test } from '@playwright/test'

test('create, edit, archive, restore, and delete a subscription across reload', async ({page})=>{
  const renewalDate = new Date().toISOString().slice(0,10)
  await page.goto('/subscriptions/new')
  await page.getByLabel('Name',{exact:true}).fill('QA Streaming')
  await page.getByLabel('Provider',{exact:true}).fill('Example Media')
  await page.locator('select[name="categoryId"]').selectOption('ott_streaming')
  await page.getByLabel('Price',{exact:true}).fill('199')
  await page.getByLabel('Next renewal',{exact:true}).fill(renewalDate)
  await page.getByRole('button',{name:'Create subscription'}).click()
  await expect(page.getByRole('heading',{name:'QA Streaming'})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'QA Streaming'})).toBeVisible()
  await page.getByRole('textbox',{name:'Search subscriptions'}).fill('QA Streaming')
  await page.getByRole('button',{name:'Search',exact:true}).click()
  await expect(page.getByRole('link',{name:'QA Streaming',exact:true})).toBeVisible()
  await page.goto('/renewals')
  await expect(page.getByRole('link',{name:'QA Streaming',exact:true})).toBeVisible()
  await page.goto('/categories')
  await expect(page.getByRole('heading',{name:'Categories',exact:true}).last()).toBeVisible()
  await page.locator('.panel').filter({hasText:'OTT & Streaming'}).getByRole('link',{name:'View subscriptions'}).click()
  await expect(page.getByRole('link',{name:'QA Streaming',exact:true})).toBeVisible()
  await page.goto('/subscriptions')
  await page.getByRole('link',{name:'QA Streaming',exact:true}).click()
  await page.getByRole('link',{name:'Edit'}).click()
  await page.getByLabel('Price',{exact:true}).fill('299')
  await page.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByText(/₹299/)).toBeVisible()
  await page.goto('/subscriptions')
  await page.getByRole('button',{name:'Archive'}).click()
  await page.getByLabel('Archived').check()
  await expect(page.getByRole('link',{name:'QA Streaming',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Restore'}).click()
  await page.getByLabel('Archived').uncheck()
  await page.getByRole('link',{name:'QA Streaming',exact:true}).click()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Delete'}).click()
  await expect(page.getByText('Your inventory is empty')).toBeVisible()
})

test('manifest and cached app shell load offline with IndexedDB data intact', async ({page, context})=>{
  await page.goto('/subscriptions/new')
  await page.getByLabel('Name',{exact:true}).fill('Offline Archive')
  await page.getByLabel('Provider',{exact:true}).fill('Local Only')
  await page.locator('select[name="categoryId"]').selectOption('ott_streaming')
  await page.getByLabel('Price',{exact:true}).fill('99')
  await page.getByRole('button',{name:'Create subscription'}).click()
  await expect(page.getByRole('heading',{name:'Offline Archive'})).toBeVisible()

  await expect(page.locator('link[rel="manifest"]')).toHaveAttribute('href',/manifest\.webmanifest/)
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  await expect.poll(()=>page.evaluate(()=>Boolean(navigator.serviceWorker.controller))).toBe(true)

  await context.setOffline(true)
  await page.goto('/subscriptions')
  await expect(page.getByRole('link',{name:'Offline Archive',exact:true})).toBeVisible()
})
